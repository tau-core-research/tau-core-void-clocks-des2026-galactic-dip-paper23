def solve_linear_growth_dual_method(
    om0: float,
    w0: float,
    wa: float,
    z_eval: np.ndarray,
    sigma8_0: float = 0.8111,
    mu_eff: float = 1.0,
) -> Dict[str, Any]:
    """
    Dual-method integration of the linear growth ODE in x = ln(a) from a_init = 1e-3 to a = 1:
        D''(x) + [2 + d(ln H)/dx] D'(x) - (3/2) * Omega_m(x) * mu_eff * D(x) = 0,
    cross-checking Method A (SciPy DOP853 adaptive) vs Method B (4000-step fixed RK4).
    Note: sigma8(a) = sigma8(a_CMB) * D(a), so when early-universe (omega_b, omega_cdm, A_s) are fixed,
    sigma8(z=0) scales proportionally to D(a=1) / D_LCDM(a=1)! We compute BOTH fixed-early-amplitude
    and fixed-sigma8_0 predictions transparently!
    """
    ode0 = 1.0 - om0
    x_init = math.log(1.0e-3)

    def bg_terms(x: float) -> Tuple[float, float]:
        a = math.exp(x)
        W = (a ** (-3.0 * (1.0 + w0 + wa))) * math.exp(3.0 * wa * (a - 1.0))
        e2 = om0 * (a ** (-3.0)) + ode0 * W
        om_a = (om0 * (a ** (-3.0))) / e2
        ode_a = 1.0 - om_a
        w_a = w0 + wa * (1.0 - a)
        dlnH_dx = -1.5 * (om_a + (1.0 + w_a) * ode_a)
        return om_a, dlnH_dx

    def rhs(x: float, y: np.ndarray) -> np.ndarray:
        D_val, dD_dx = float(y[0]), float(y[1])
        om_a, dlnH_dx = bg_terms(x)
        d2D = -(2.0 + dlnH_dx) * dD_dx + 1.5 * om_a * mu_eff * D_val
        return np.array([dD_dx, d2D], dtype=float)

    # Initial condition in deep matter domination (a = 1e-3): D(a) = a, dD/dx = a
    a_i = math.exp(x_init)
    p_grow = 0.25 * (-1.0 + math.sqrt(1.0 + 24.0 * mu_eff))
    y0 = np.array([a_i**p_grow, p_grow * (a_i**p_grow)], dtype=float)

    x_targets = np.sort(np.unique(np.append(-np.log1p(z_eval), 0.0)))
    sol_dop = integrate.solve_ivp(
        rhs, (x_init, 0.0), y0=y0, t_eval=x_targets, method="DOP853", rtol=1e-12, atol=1e-14
    )
    assert sol_dop.success

    # Method B: Independent 4000-step RK4
    n_rk = 4000
    x_rk = np.linspace(x_init, 0.0, n_rk)
    dx = float(x_rk[1] - x_rk[0])
    y_rk = np.zeros((n_rk, 2), dtype=float)
    y_rk[0] = y0
    for i in range(n_rk - 1):
        st = y_rk[i]
        xv = float(x_rk[i])
        k1 = rhs(xv, st)
        k2 = rhs(xv + 0.5 * dx, st + 0.5 * dx * k1)
        k3 = rhs(xv + 0.5 * dx, st + 0.5 * dx * k2)
        k4 = rhs(xv + dx, st + dx * k3)
        y_rk[i + 1] = st + (dx / 6.0) * (k1 + 2.0 * k2 + 2.0 * k3 + k4)

    D_dop_0 = float(sol_dop.y[0, -1])
    D_rk_0 = float(y_rk[-1, 0])
    dual_growth_diff = abs(D_dop_0 - D_rk_0)
    assert dual_growth_diff < 1e-10

    D_interp = np.interp(-np.log1p(z_eval), sol_dop.t, sol_dop.y[0])
    dDdx_interp = np.interp(-np.log1p(z_eval), sol_dop.t, sol_dop.y[1])
    f_z = dDdx_interp / D_interp
    D_norm = D_interp / D_dop_0
    fs8_fixed_s80 = f_z * sigma8_0 * D_norm

    return {
        "D_at_a1_raw": D_dop_0,
        "dual_solver_abs_diff": dual_growth_diff,
        "f_z": f_z,
        "D_norm": D_norm,
        "fsigma8_at_fixed_s80": fs8_fixed_s80,
    }


